class JamConnect {
  constructor(toneInstance) {
    this.Tone = toneInstance;
    this.isHost = false;

    // Host state: stores active guest peer connections & data channels
    // Map<peerId, { pc: RTCPeerConnection, channel: RTCDataChannel }>
    this.peers = new Map();
    this.pendingPeerId = null;
    this.pendingPc = null;

    // Guest state
    this.guestPc = null;
    this.guestChannel = null;
    this.timeOffset = 0; // Difference between Host clock and Guest clock

    // Event listener callbacks
    this.onPeerConnected = null;
    this.onPeerDisconnected = null;
    this.onPadTriggered = null; // (instrument, pitch, velocity, when)
  }

  // ==========================================
  // HOST METHODS
  // ==========================================

  /**
   * Host prepares an invitation token (SDP Offer) for ONE new guest.
   * Return value is a Base64 string to encode into a QR code.
   */
  async prepareGuestInvitation() {
    this.isHost = true;
    inviteBtn.disabled = true;
    const peerId = 'peer_' + Math.random().toString(36).substring(2, 9);
    const pc = new RTCPeerConnection({ iceServers: []});
   // { urls: 'stun:stun.l.google.com:19302' }, { urls: 'stun:stun1.l.google.com:19302' },] });

    // Use unordered, maxRetransmits: 0 for minimal latency (UDP style)
    const channel = pc.createDataChannel('jam-sync', {
      ordered: false,
      maxRetransmits: 0
    });

    this.pendingPeerId = peerId;
    this.pendingPc = pc;
    this._attachChannelEvents(channel, peerId);

    const offer = await pc.createOffer();
    await pc.setLocalDescription(offer);

    return new Promise((resolve) => {
      pc.onicecandidate = (e) => {
        if (!e.candidate) {
          const payload = {
            peerId: peerId,
            sdp: pc.localDescription
          };
          resolve(btoa(JSON.stringify(payload)));
        }
      };
    });
  }

  /**
   * Host scans the Answer QR code generated by the guest.
   */
  async acceptGuestAnswer(encodedAnswer) {
    const { peerId, sdp } = JSON.parse(atob(encodedAnswer));
    if (peerId !== this.pendingPeerId || !this.pendingPc) {
      throw new Error('Mismatched peer handshake session.');
    }

    await this.pendingPc.setRemoteDescription(new RTCSessionDescription(sdp));
    this.pendingPeerId = null;
    this.pendingPc = null;
  }

  // ==========================================
  // GUEST METHODS
  // ==========================================

  /**
   * Guest scans the Host's QR code (SDP Offer) and generates an SDP Answer string.
   */
  async joinHost(encodedOffer) {
    this.isHost = false;
    const { peerId, sdp } = JSON.parse(atob(encodedOffer));

    this.guestPc = new RTCPeerConnection({ iceServers: [] });

    this.guestPc.ondatachannel = (event) => {
      this.guestChannel = event.channel;
      this._attachChannelEvents(this.guestChannel, 'HOST');
    };

    await this.guestPc.setRemoteDescription(new RTCSessionDescription(sdp));
    const answer = await this.guestPc.createAnswer();
    await this.guestPc.setLocalDescription(answer);

    return new Promise((resolve) => {
      this.guestPc.onicecandidate = (e) => {
        if (!e.candidate) {
          const payload = {
            peerId: peerId,
            sdp: this.guestPc.localDescription
          };
          resolve(btoa(JSON.stringify(payload)));
        }
      };
    });
  }

  // ==========================================
  // MESSAGING & RELAY LOGIC
  // ==========================================

  _attachChannelEvents(channel, peerId) {
    channel.onopen = () => {
      if (this.isHost) {
        this.peers.set(peerId, { pc: this.pendingPc, channel: channel });
        if (this.onPeerConnected) this.onPeerConnected(peerId);
        
        // Immediately sync Tone.Transport status to the newly connected guest
        this._sendTo(channel, {
          type: 'TRANSPORT_STATE',
          state: this.Tone.Transport.state,
          bpm: this.Tone.Transport.bpm.value,
          seconds: this.Tone.Transport.seconds,
          hostAudioTime: this.Tone.now()
        });

        // Start ping routine for clock synchronization
        this._measureClockOffset(channel);
      } else {
        if (this.onPeerConnected) this.onPeerConnected('HOST');
      }
    };

    channel.onclose = () => {
      if (this.isHost) {
        this.peers.delete(peerId);
        if (this.onPeerDisconnected) this.onPeerDisconnected(peerId);
      }
    };

    channel.onmessage = (e) => {
      const msg = JSON.parse(e.data);
      this._routeMessage(msg, peerId);
    };
  }

  _routeMessage(msg, senderId) {
    switch (msg.type) {
      case 'PING':
        if (this.guestChannel) {
          this._sendTo(this.guestChannel, {
            type: 'PONG',
            clientSendTime: msg.clientSendTime,
            hostReceiveTime: performance.now()
          });
        }
        break;

      case 'PONG':
        if (this.isHost) {
          const now = performance.now();
          const rtt = now - msg.clientSendTime;
          // One-way transit time estimate: rtt / 2
          const guestTimeEstimate = msg.hostReceiveTime + (rtt / 2);
          const offset = guestTimeEstimate - now;
          
          const peer = this.peers.get(senderId);
          if (peer) peer.timeOffset = offset;
        }
        break;

      case 'TRANSPORT_STATE':
        // Guest adopts Host's tempo and playback state
        this.Tone.Transport.bpm.value = msg.bpm;
        if (msg.state === 'started') {
          // Compensate start position with network drift
          const elapsedSinceHostEvent = this.Tone.now() - msg.hostAudioTime;
          this.Tone.Transport.seconds = msg.seconds + Math.max(0, elapsedSinceHostEvent);
          this.Tone.Transport.start();
        } else {
          this.Tone.Transport.stop();
          this.Tone.Transport.seconds = msg.seconds;
        }
        break;

      case 'PAD_PLAY':
        // 1. Trigger local synthesizer/sampler
        if (this.onPadTriggered) {
          this.onPadTriggered(msg.instrument, msg.note, msg.velocity, msg.scheduledTime);
        }

        // 2. If Host received this from Guest, relay to ALL other guests
        if (this.isHost) {
          for (const [id, peer] of this.peers.entries()) {
            if (id !== senderId && peer.channel.readyState === 'open') {
              this._sendTo(peer.channel, msg);
            }
          }
        }
        break;
    }
  }

  _measureClockOffset(channel) {
    this._sendTo(channel, {
      type: 'PING',
      clientSendTime: performance.now()
    });
  }

  _sendTo(channel, obj) {
    if (channel && channel.readyState === 'open') {
      channel.send(JSON.stringify(obj));
    }
  }

  // ==========================================
  // PLAYBACK & QUANTIZED LIVE PERFORMANCE
  // ==========================================

  /**
   * Host-only: Starts or stops all connected devices simultaneously.
   */
  startTransport(bpm = 120) {
    if (!this.isHost) return;
    this.Tone.Transport.bpm.value = bpm;
    
    // Schedule 150ms in the future so guests receive packet before playback starts
    const futureStartTime = this.Tone.now() + 0.15;
    this.Tone.Transport.start(futureStartTime);

    for (const peer of this.peers.values()) {
      this._sendTo(peer.channel, {
        type: 'TRANSPORT_STATE',
        state: 'started',
        bpm: bpm,
        seconds: 0,
        hostAudioTime: futureStartTime
      });
    }
  }

  stopTransport() {
    if (!this.isHost) return;
    this.Tone.Transport.stop();
    for (const peer of this.peers.values()) {
      this._sendTo(peer.channel, {
        type: 'TRANSPORT_STATE',
        state: 'stopped',
        bpm: this.Tone.Transport.bpm.value,
        seconds: 0,
        hostAudioTime: this.Tone.now()
      });
    }
  }

  /**
   * Triggers a drum pad or 303 note with gentle quantization.
   * Can be called by Host OR Guest.
   *
   * @param {string} instrument - '303', 'kick', 'snare', 'hihat'
   * @param {string} note - e.g. 'C2', 'G2'
   * @param {number} velocity - 0.0 to 1.0
   * @param {number} snapStrength - 0.0 (no snap) to 1.0 (hard snap). Default 0.65 (gentle)
   */
  triggerPad(instrument, note = 'C2', velocity = 0.8, snapStrength = 0.65) {
    const now = this.Tone.now();
    const bpm = this.Tone.Transport.bpm.value;
    
    // Duration of a 16th note subdivision
    const sixteenthDuration = (60 / bpm) / 4;
    
    // Position within the current 16th note interval
    const remainder = now % sixteenthDuration;
    let deltaToNearestGrid = (remainder > sixteenthDuration / 2) 
      ? (sixteenthDuration - remainder) 
      : -remainder;

    // Apply gentle snap factor: pull the note closer to the 16th grid
    // If it falls slightly early/late, we shift it by snapStrength percentage
    let scheduledTime = now + (deltaToNearestGrid * snapStrength);

    // AudioContext can never schedule in the past
    if (scheduledTime < now) scheduledTime = now;

    // 1. Play on this device immediately at the scheduled time
    if (this.onPadTriggered) {
      this.onPadTriggered(instrument, note, velocity, scheduledTime);
    }

    // 2. Broadcast to network
    const payload = {
      type: 'PAD_PLAY',
      instrument,
      note,
      velocity,
      scheduledTime
    };

    if (this.isHost) {
      // Host relays to all connected guests
      for (const peer of this.peers.values()) {
        this._sendTo(peer.channel, payload);
      }
    } else if (this.guestChannel) {
      // Guest sends to Host (who will relay to other guests)
      this._sendTo(this.guestChannel, payload);
    }
  }
}

